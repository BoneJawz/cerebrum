from __future__ import annotations

import csv, json, time
from pathlib import Path
import numpy as np
from .stimuli import make_task
from .network import STDPAssociator
from .assessment import evaluate

EXPOSURES = (0, 1, 5, 10, 20, 50)
SEEDS = (42, 43, 44, 45, 46)


def run(outdir: str | Path = "results/association_baseline") -> list[dict]:
    out = Path(outdir); out.mkdir(parents=True, exist_ok=True)
    rows: list[dict] = []
    for seed in SEEDS:
        for exposures in EXPOSURES:
            task = make_task(seed, exposures)
            for condition in ("no_learning", "correct", "mismatched"):
                net = STDPAssociator(seed=seed, learning=condition != "no_learning")
                start = time.perf_counter()
                for ep in task.episodes:
                    target = None if condition == "no_learning" else ep.target
                    if condition == "mismatched": target = (target + 1) % 3
                    net.present(ep.cue, target)
                accuracy = evaluate(net, task.permutation)
                rows.append({"seed": seed, "exposures": exposures, "condition": condition,
                             "accuracy": accuracy, "mean_weight": float(np.mean(net.weights())),
                             "weight_delta": float(np.mean(np.abs(net.weights() - 0.1))),
                             "cpu_seconds": time.perf_counter() - start})
    with (out / "trial_results.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys()); writer.writeheader(); writer.writerows(rows)
    curve = []
    for exp in EXPOSURES:
        for cond in ("no_learning", "correct", "mismatched"):
            vals = [r["accuracy"] for r in rows if r["exposures"] == exp and r["condition"] == cond]
            curve.append({"exposures": exp, "condition": cond, "mean_accuracy": float(np.mean(vals)),
                          "std_accuracy": float(np.std(vals, ddof=1))})
    with (out / "learning_curve.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=curve[0].keys()); writer.writeheader(); writer.writerows(curve)
    config = {"seeds": list(SEEDS), "exposures": list(EXPOSURES), "n_items": 3,
              "mechanism": "pair-based additive STDP in Brian2 2.6.0", "chance": 1/3}
    (out / "configuration.json").write_text(json.dumps(config, indent=2))
    try:
        import matplotlib.pyplot as plt
        for cond in ("no_learning", "correct", "mismatched"):
            c = [r for r in curve if r["condition"] == cond]
            plt.plot([r["exposures"] for r in c], [r["mean_accuracy"] for r in c], marker="o", label=cond)
        plt.axhline(1/3, color="k", linestyle="--", label="chance")
        plt.xlabel("teaching exposures per association"); plt.ylabel("recall accuracy"); plt.legend(); plt.tight_layout()
        plt.savefig(out / "learning_curve.png", dpi=140); plt.close()
    except ImportError:
        pass
    (out / "ASSOCIATION_BASELINE_REPORT.md").write_text(
        "# Literature-based association baseline\n\n"
        "This milestone tests a three-way arbitrary auditory-spike to visual-output association. "
        "Teaching pairs an auditory spike with a delayed teacher spike; recall removes the teacher and scores output spikes. "
        "The permutation is randomized per seed and only the raw spike events enter Brian2. Controls are no-learning and mismatched teacher.\n\n"
        "This is a mechanism validation, not evidence of biological equivalence or semantic grounding. "
        "Inspect `trial_results.csv` and `learning_curve.csv`; all numbers are generated by the run.\n")
    return rows


if __name__ == "__main__":
    run()
